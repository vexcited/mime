static void secure(PVOID object, const UCHAR *descriptor)
{
    SD_BLOB *sd;
    if (!NT_SUCCESS(SeSdCapture(descriptor, KernelMode, &sd)))
        return;
    ObAttachSecurity(object, nullptr);
    ObStoreSecurity(object, sd);
    SeSdDereference(sd);
}

static void known_dll(POBJECT_DIRECTORY directory, PCWSTR files, PCWSTR name, BOOLEAN wow64)
{
    WCHAR path[96];
    _snwprintf(path, RTL_NUMBER_OF(path) - 1, L"\\SystemRoot\\%ws\\%ws", files, name);
    path[RTL_NUMBER_OF(path) - 1] = 0;
    UNICODE_STRING file_name, leaf;
    RtlInitUnicodeString(&file_name, path);
    RtlInitUnicodeString(&leaf, name);
    PFILE_OBJECT file;
    if (!NT_SUCCESS(IopOpenFileObject(&file_name, FILE_READ_DATA | FILE_EXECUTE | SYNCHRONIZE, FILE_NON_DIRECTORY_FILE, &file)))
        return;
    /*
     * like SmpInitializeKnownDllsInternal for the value _wow64cpu of the KnownDlls key: a name with a leading _ is
     * made with SEC_IMAGE | 0x100000, and the kernel draws its base below 4 GiB, where 32-bit code reaches it.
     */
    ULONG flags = !wow64 && !_wcsicmp(name, L"wow64cpu.dll") ? MI_IMAGE_BASE_BELOW_4GB : 0;
    PSECTION section;
    NTSTATUS status = MiCreateImageSectionEx(file, flags, &section);
    ObDereferenceObject(file);
    if (!NT_SUCCESS(status))
        return;
    /* the reference of the creation keeps the permanent section. */
    if (OBJECT_TO_HEADER(section)->Directory || !NT_SUCCESS(ObInsertIntoDirectory(directory, section, &leaf))) {
        ObDereferenceObject(section);
        return;
    }
    OBJECT_TO_HEADER(section)->Flags |= OB_FLAG_PERMANENT;
    secure(section, g_section_security);
}

static void known_dlls(PCWSTR directory_name, PCWSTR files, BOOLEAN wow64)
{
    POBJECT_DIRECTORY directory = nullptr;
    ObCreateDirectory(directory_name, &directory);
    if (!directory)
        return;
    secure(directory, g_directory_security);
    for (ULONG i = 0; i < RTL_NUMBER_OF(g_names); i++)
        if (!wow64 || _wcsnicmp(g_names[i], L"wow64", 5))
            known_dll(directory, files, g_names[i], wow64);

    WCHAR link[64], target[RTL_NUMBER_OF(SharedUserData->NtSystemRoot) + 16];
    _snwprintf(link, RTL_NUMBER_OF(link) - 1, L"%ws\\KnownDllPath", directory_name);
    link[RTL_NUMBER_OF(link) - 1] = 0;
    _snwprintf(target, RTL_NUMBER_OF(target) - 1, L"%ws\\%ws", SharedUserData->NtSystemRoot, files);
    target[RTL_NUMBER_OF(target) - 1] = 0;
    UNICODE_STRING link_name;
    RtlInitUnicodeString(&link_name, link);
    PVOID object;
    if (NT_SUCCESS(ObCreateSymbolicLink(link, target)) &&
        NT_SUCCESS(ObLookupObjectName(&link_name, nullptr, OBJ_OPENLINK, ObSymbolicLinkType, KernelMode, nullptr, &object))) {
        secure(object, g_link_security);
        ObDereferenceObject(object);
    }
    ObDereferenceObject(directory);
}

void ExCreateKnownDlls(void)
{
    known_dlls(L"\\KnownDlls", L"System32", FALSE);
    if (PspWow64NtdllSection)
        known_dlls(L"\\KnownDlls32", L"SysWOW64", TRUE);
}
