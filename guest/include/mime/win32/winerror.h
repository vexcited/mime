/* hresults. */
typedef LONG HRESULT;

#define SEVERITY_SUCCESS 0
#define SEVERITY_ERROR 1
#define FACILITY_NULL 0
#define FACILITY_RPC 1
#define FACILITY_DISPATCH 2
#define FACILITY_STORAGE 3
#define FACILITY_ITF 4
#define FACILITY_WIN32 7
#define FACILITY_WINDOWS 8
#define FACILITY_NT_BIT 0x10000000

#define SUCCEEDED(hr) (((HRESULT)(hr)) >= 0)
#define FAILED(hr) (((HRESULT)(hr)) < 0)
#define IS_ERROR(status) (((ULONG)(status)) >> 31 == SEVERITY_ERROR)
#define HRESULT_CODE(hr) ((hr) & 0xFFFF)
#define SCODE_CODE(sc) ((sc) & 0xFFFF)
#define HRESULT_FACILITY(hr) (((hr) >> 16) & 0x1FFF)
#define SCODE_FACILITY(sc) (((sc) >> 16) & 0x1FFF)
#define HRESULT_SEVERITY(hr) (((hr) >> 31) & 0x1)
#define SCODE_SEVERITY(sc) (((sc) >> 31) & 0x1)
#define MAKE_HRESULT(sev, fac, code) ((HRESULT)(((ULONG)(sev) << 31) | ((ULONG)(fac) << 16) | ((ULONG)(code))))
#define MAKE_SCODE(sev, fac, code) ((LONG)(((ULONG)(sev) << 31) | ((ULONG)(fac) << 16) | ((ULONG)(code))))
#define HRESULT_FROM_NT(x) ((HRESULT)((x) | FACILITY_NT_BIT))

static inline HRESULT HRESULT_FROM_WIN32(ULONG x)
{
    return (HRESULT)x <= 0 ? (HRESULT)x : (HRESULT)((x & 0x0000FFFF) | (FACILITY_WIN32 << 16) | 0x80000000);
}

