typedef struct tagVARIANT VARIANT, *LPVARIANT, VARIANTARG, *LPVARIANTARG;
struct tagVARIANT {
    union {
        struct {
            VARTYPE vt;
            WORD wReserved1;
            WORD wReserved2;
            WORD wReserved3;
            union {
                LONGLONG llVal;
                LONG lVal;
                BYTE bVal;
                SHORT iVal;
                FLOAT fltVal;
                DOUBLE dblVal;
                VARIANT_BOOL boolVal;
                SCODE scode;
                CY cyVal;
                DATE date;
                BSTR bstrVal;
                IUnknown *punkVal;
                IDispatch *pdispVal;
                SAFEARRAY *parray;
                CHAR cVal;
                USHORT uiVal;
                ULONG ulVal;
                ULONGLONG ullVal;
                INT intVal;
                UINT uintVal;
                PVOID byref;
                VARIANT *pvarVal;
                BSTR *pbstrVal;
                IUnknown **ppunkVal;
                SAFEARRAY **pparray;
                struct {
                    PVOID pvRecord;
                    IRecordInfo *pRecInfo;
                };
            };
        };
        DECIMAL decVal;
    };
};
MIME_STATIC_ASSERT(sizeof(VARIANT) == (sizeof(void *) == 4 ? 16 : 24), "VARIANT size");

