/* messages the system keeps for itself, which a program cannot post. */
static const MSG_RANGE g_private[] = {
    {0x3C, 0x3C}, {0x2E6, 0x2E6}, {0x2ED, 0x2EE}, {0x2FB, 0x2FB}, {0x32C, 0x32F}, {0x341, 0x349},
};

/* messages that exist only in the window manager: sending one from a program does nothing. */
static const MSG_RANGE g_kernel_only[] = {
    {0x3A, 0x3A},   {0x3C, 0x3C},   {0x70, 0x70},   {0x8C, 0x8C},   {0x11B, 0x11B}, {0x238, 0x23D}, {0x2C8, 0x2C9},
    {0x2E6, 0x2E6}, {0x2FB, 0x2FB}, {0x314, 0x314}, {0x324, 0x325}, {0x329, 0x329}, {0x32C, 0x32F}, {0x343, 0x343},
    {0x345, 0x345}, {0x347, 0x347},
};

static inline BOOLEAN MimeMsgInRanges(const MSG_RANGE *r, ULONG count, UINT msg)
{
    for (ULONG i = 0; i < count; i++)
        if (msg >= r[i].First && msg <= r[i].Last)
            return TRUE;
    return FALSE;
}

static inline BOOLEAN MimeMsgIsSyncOnly(UINT msg, WPARAM wparam, BOOLEAN post)
{
    if (msg >= 0x400)
        return FALSE;
    if (MimeMsgInRanges(g_sync_only, RTL_NUMBER_OF(g_sync_only), msg))
        return TRUE;
    /* a device change or a power broadcast with data carries a pointer. */
    return (msg == 0x219 || (post && msg == 0x218)) && (wparam & 0x8000);
}

static inline BOOLEAN MimeMsgIsPrivate(UINT msg)
{
    return msg < 0x400 && MimeMsgInRanges(g_private, RTL_NUMBER_OF(g_private), msg);
}

static inline BOOLEAN MimeMsgKernelOnly(UINT msg)
{
    return MimeMsgInRanges(g_kernel_only, RTL_NUMBER_OF(g_kernel_only), msg);
}

