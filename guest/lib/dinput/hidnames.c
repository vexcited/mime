static USHORT page_base(USHORT page)
{
    switch (page) {
    case 0x01:
        return 0x600;
    case 0x02:
        return 0x800;
    case 0x03:
        return 0xA00;
    case 0x04:
        return 0xC00;
    case 0x05:
        return 0xE00;
    case 0x07:
        return 0x1800;
    case 0x08:
        return 0x1000;
    case 0x0B:
        return 0x1200;
    case 0x0C:
        return 0x1400;
    case 0x0D:
        return 0x1600;
    case 0x0F:
        return 0x1A00;
    default:
        return 0;
    }
}

const WCHAR *DiHidUsageName(USHORT page, USHORT usage)
{
    USHORT base = page_base(page);
    if (!base || usage >= 0x200)
        return nullptr;
    USHORT id = (USHORT)(base + usage);
    ULONG lo = 0, hi = RTL_NUMBER_OF(NAMES);
    while (lo < hi) {
        ULONG mid = (lo + hi) / 2;
        if (NAMES[mid].id == id)
            return NAMES[mid].name;
        if (NAMES[mid].id < id)
            lo = mid + 1;
        else
            hi = mid;
    }
    return nullptr;
}
