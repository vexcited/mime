/*
 * the guest-visible microsoft hypervisor. arm64 guests reach it with `hvc #0` and the SMCCC function
 * below, or with the older `hvc #1`, which carries the hypercall input value in x0.
 */
#ifndef MIME_HYPERV_H
#define MIME_HYPERV_H

#define MIME_HV_SMCCC_HYPERCALL 0x46000001ull

/* the hypercall input value. */
#define MIME_HV_FAST (1ull << 16)
#define MIME_HV_REP_COUNT(input) (((input) >> 32) & 0xFFF)
#define MIME_HV_REP_START(input) (((input) >> 48) & 0xFFF)
#define MIME_HV_REP_VALUE(count, start) (((uint64_t)(count) << 32) | ((uint64_t)(start) << 48))

#define MIME_HV_PARTITION_SELF (~0ull)
#define MIME_HV_PARTITION_ROOT 0ull
#define MIME_HV_VTL_ROOT 0

/* windows nt 10.0, its build, as the guest os id register carries it. */
#define MIME_HV_WINDOWS_OS_ID 0x0001040A000066BCull

/* the hypercall result value: a status below bit 16, the reps done from bit 32. */
#define MIME_HV_STATUS(result) ((result) & 0xFFFF)
#define MIME_HV_RESULT(status, reps) ((uint64_t)(status) | ((uint64_t)(reps) << 32))

#define MIME_HV_SUCCESS 0x0
#define MIME_HV_INVALID_HYPERCALL_CODE 0x2
#define MIME_HV_INVALID_HYPERCALL_INPUT 0x3
#define MIME_HV_INVALID_ALIGNMENT 0x4
#define MIME_HV_INVALID_PARAMETER 0x5
#define MIME_HV_ACCESS_DENIED 0x6
#define MIME_HV_INVALID_PARTITION_ID 0xD
#define MIME_HV_INVALID_VP_INDEX 0xE
#define MIME_HV_INVALID_CONNECTION_ID 0x12
#define MIME_HV_INVALID_VP_STATE 0x15
#define MIME_HV_INVALID_REGISTER_VALUE 0x50
#define MIME_HV_UNKNOWN_PROPERTY 0x9

/* the call codes, and the privileges and features the machine reports with them. */
#define MIME_HV_CALL_SWITCH_VIRTUAL_ADDRESS_SPACE 0x1
#define MIME_HV_CALL_FLUSH_VIRTUAL_ADDRESS_SPACE 0x2
#define MIME_HV_CALL_FLUSH_VIRTUAL_ADDRESS_LIST 0x3
#define MIME_HV_CALL_NOTIFY_LONG_SPIN_WAIT 0x8
#define MIME_HV_CALL_SEND_SYNTHETIC_CLUSTER_IPI 0xB
#define MIME_HV_CALL_ENABLE_PARTITION_VTL 0xD
#define MIME_HV_CALL_ENABLE_VP_VTL 0xF
#define MIME_HV_CALL_VTL_CALL 0x11
#define MIME_HV_CALL_VTL_RETURN 0x12
#define MIME_HV_CALL_FLUSH_VIRTUAL_ADDRESS_SPACE_EX 0x13
#define MIME_HV_CALL_FLUSH_VIRTUAL_ADDRESS_LIST_EX 0x14
#define MIME_HV_CALL_SEND_SYNTHETIC_CLUSTER_IPI_EX 0x15
#define MIME_HV_CALL_GET_PARTITION_PROPERTY 0x44
#define MIME_HV_CALL_SET_PARTITION_PROPERTY 0x45
#define MIME_HV_CALL_GET_PARTITION_ID 0x46
#define MIME_HV_CALL_GET_VP_REGISTERS 0x50
#define MIME_HV_CALL_SET_VP_REGISTERS 0x51
#define MIME_HV_CALL_TRANSLATE_VIRTUAL_ADDRESS 0x52
#define MIME_HV_CALL_CLEAR_VIRTUAL_INTERRUPT 0x56
#define MIME_HV_CALL_POST_MESSAGE 0x5C
#define MIME_HV_CALL_SIGNAL_EVENT 0x5D
#define MIME_HV_CALL_ASSERT_VIRTUAL_INTERRUPT 0x94
#define MIME_HV_CALL_START_VP 0x99
#define MIME_HV_CALL_GET_VP_INDEX_FROM_APIC_ID 0x9A
#define MIME_HV_CALL_FLUSH_GPA_SPACE 0xAF
#define MIME_HV_CALL_FLUSH_GPA_LIST 0xB0
#define MIME_HV_CALL_DISABLE_HYP_EX 0x10F

#define MIME_HV_PRIVILEGE_FLAGS 0x99F77FFFULL /* and 0x19 in the high half. */

/* the registers HvCallGetVpRegisters and HvCallSetVpRegisters name, as 128-bit values. */
#define MIME_HV_REG_HYPERVISOR_VERSION 0x100
#define MIME_HV_REG_PRIVILEGES_AND_FEATURES 0x200
#define MIME_HV_REG_FEATURES 0x201
#define MIME_HV_REG_IMPLEMENTATION_LIMITS 0x202
#define MIME_HV_REG_HARDWARE_FEATURES 0x203
#define MIME_HV_REG_GUEST_CRASH_P0 0x210
#define MIME_HV_REG_GUEST_CRASH_P1 0x211
#define MIME_HV_REG_GUEST_CRASH_P2 0x212
#define MIME_HV_REG_GUEST_CRASH_P3 0x213
#define MIME_HV_REG_GUEST_CRASH_P4 0x214
#define MIME_HV_REG_GUEST_CRASH_CTL 0x215
#define MIME_HV_REG_VP_RUNTIME 0x90000
#define MIME_HV_REG_GUEST_OS_ID 0x90002
#define MIME_HV_REG_VP_INDEX 0x90003
#define MIME_HV_REG_TIME_REF_COUNT 0x90004
#define MIME_HV_REG_CPU_MANAGEMENT_VERSION 0x90007
#define MIME_HV_REG_VP_ASSIST_PAGE 0x90013
#define MIME_HV_REG_REFERENCE_TSC 0x90017

/* partition properties HvCallGetPartitionProperty answers. */
#define MIME_HV_PROPERTY_PRIVILEGE_FLAGS 0x10000
#define MIME_HV_PROPERTY_SYNTHETIC_PROC_FEATURES 0x10001
#define MIME_HV_PROPERTY_REFERENCE_TIME 0x30005
#define MIME_HV_PROPERTY_ISOLATION_STATE 0x5000C
#define MIME_HV_PROPERTY_PHYSICAL_ADDRESS_BITS 0x50010
#define MIME_HV_PROPERTY_PROCESSOR_VENDOR 0x60000
#define MIME_HV_PROPERTY_COMPATIBILITY_VERSION 0x60005
#define MIME_HV_PROPERTY_ADDRESS_WIDTH 0x60006
#define MIME_HV_PROPERTY_GUEST_OS_ID 0x70000

#endif
